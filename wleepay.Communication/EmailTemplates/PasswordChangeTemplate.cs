using System;
using System.Collections.Generic;
using System.Text;

namespace wleepay.Communication.EmailTemplates
{
    public class PasswordChangeTemplate
    {
        public class PasswordChangeTemplateForSystemAdmin
        {

            public string StaffEmail { get; set; }
            public string StaffPhoneNumber { get; set; }
            public string StaffFirstName { get; set; }
            public string StaffPermissions { get; set; }

            public string GenerateHtml()
            {
                return $@"Dear Wleepay Administrator,
                
                The following Wleepay staff has changed their portal login password. This is only a notification, but you may consider investigating if necessary. The staff has also been notified.  
                •	{StaffFirstName} 
                •	{StaffEmail}
                •	{StaffPhoneNumber}
               
                Thank you.
                (Please Do not reply to this email. This email was automatically generated by the Wleepay portal notification system)";

            }
        }

        public class PasswordChangeTemplateForStaff
        {

            public string StaffEmail { get; set; }
            public string StaffPhoneNumber { get; set; }
            public string StaffFirstName { get; set; }
            public string StaffPermissions { get; set; }

            public string GenerateHtml()
            {
                return $@"Dear {StaffFirstName},

                Your Wleepay portal login account password for {StaffEmail} has changed. Please contact the system administrator if you did not make this password change. 
                Thank you.

                (Please Do not reply to this email. This email was automatically generated by the Wleepay portal notification system)";

            }
        }
    }
}
