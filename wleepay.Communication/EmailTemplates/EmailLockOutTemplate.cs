using System;
using System.Collections.Generic;
using System.Text;

namespace wleepay.Communication.EmailTemplates
{
    public class EmailLockOutTemplate
    {
        public class EmailLockOutTemplateForSystemAdmin
        {

            public string StaffEmail { get; set; }
            public string StaffPhoneNumber { get; set; }
            public string StaffFirstName { get; set; }
            public string StaffPermissions { get; set; }

            public string GenerateHtml()
            {
                return $@"Dear Wleepay Administrator,
                
                The following Wleepay staff ‘s portal login account has been locked after 3 unsuccessful login attempts. Please proceed to investigate this incident and unlock the staff’s account if necessary. The staff has also been notified: 
                •	{StaffFirstName} 
                •	{StaffEmail}
                •	{StaffPhoneNumber}
                
                Thank you.
                (Please Do not reply to this email. This email was automatically generated by the Wleepay portal notification system)";
           
            }
        }

        public class EmailLockOutTemplateForStaff
        {

            public string StaffEmail { get; set; }
            public string StaffPhoneNumber { get; set; }
            public string StaffFirstName { get; set; }
            public string StaffPermissions { get; set; }

            public string GenerateHtml()
            {
                return $@"Dear {StaffFirstName},
                Your Wleepay portal account is now active for {StaffEmail}. You may now login to your account using the credentials you provided. 
                
                Thank you.
                (Please Do not reply to this email. This email was automatically generated by the Wleepay portal notification system)";

            }
        }
    }
}
