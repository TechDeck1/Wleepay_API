using System;
using System.Collections.Generic;
using System.Text;

namespace wleepay.Communication.EmailTemplates
{
    public class AccountDeactivatedTemplate
    {

        public class AccountDeactivatedTemplateForSystemAdmin
        {

            public string StaffEmail { get; set; }
            public string StaffPhoneNumber { get; set; }
            public string StaffFirstName { get; set; }
            public string StaffPermissions { get; set; }

            public string GenerateHtml()
            {
                return $@"Dear Wleepay Administrator,
            
            The following Wleepay staff’s portal account is now DeActivated. This account may only be activated by an Administrator. This is only a notification. The staff has also been notified.
            •	{StaffFirstName} 
            •	{StaffEmail}
            •	{StaffPhoneNumber}

            Thank you.
            (Please Do not reply to this email. This email was automatically generated by the Wleepay portal notification system)";

            }
        }

        public class AccountDeactivatedTemplateForStaff
        {

            public string StaffEmail { get; set; }
            public string StaffPhoneNumber { get; set; }
            public string StaffFirstName { get; set; }
            public string StaffPermissions { get; set; }

            public string GenerateHtml()
            {
                return $@"Dear {StaffFirstName},
               
                Your Wleepay portal account is now DeActivated for {StaffEmail}. Please contact the Wleepay Administrator. You will no longer be able to login to the portal. 
               
                Thank you.
                (Please Do not reply to this email. This email was automatically generated by the Wleepay portal notification system)";
            }
        }

    }
}
